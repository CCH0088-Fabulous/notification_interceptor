package dev.poc.notifinterceptor.domain

/** 测试用快照构造器，集中默认值，避免每个用例重复 20 个参数。 */
fun testSnapshot(
    packageName: String = "com.demo.shop",
    key: String = "0|$packageName|1|null|10001",
    title: String? = "标题",
    text: String? = "正文",
    bigText: String? = null,
    textLines: List<String> = emptyList(),
    channelId: String? = "default",
    isOngoing: Boolean = false,
    isClearable: Boolean = true,
    postTime: Long = 1_760_000_000_000L,
): NotificationSnapshot = NotificationSnapshot(
    key = key,
    id = 1,
    packageName = packageName,
    appLabel = "演示",
    postTime = postTime,
    title = title,
    text = text,
    bigText = bigText,
    textLines = textLines,
    subText = null,
    tickerText = null,
    category = "msg",
    channelId = channelId,
    channelName = "默认",
    groupKey = null,
    isGroupSummary = false,
    isOngoing = isOngoing,
    isClearable = isClearable,
    priority = 0,
    progress = -1,
    extras = emptyMap(),
)

fun testRule(
    id: String,
    action: RuleAction = RuleAction.INTERCEPT,
    mode: MatchMode = MatchMode.ALL,
    packages: List<String> = emptyList(),
    keywords: List<String> = emptyList(),
    titleRegex: String? = null,
    textRegex: String? = null,
    channelIds: List<String> = emptyList(),
    isOngoing: Boolean? = null,
    isClearable: Boolean? = null,
    quietHours: QuietHours? = null,
    enabled: Boolean = true,
): RuleSpec = RuleSpec(
    id = id,
    name = id,
    enabled = enabled,
    action = action,
    mode = mode,
    packages = packages,
    keywordsAny = keywords,
    titleRegex = titleRegex,
    textRegex = textRegex,
    channelIds = channelIds,
    isOngoing = isOngoing,
    isClearable = isClearable,
    quietHours = quietHours,
)
